-- Agenda personal · Esquema para Supabase (Postgres)
-- Ejecútalo UNA vez: Supabase → SQL Editor → New query → pegar → Run.

create table if not exists public.calendars (
  id      bigint generated by default as identity primary key,
  name    text not null,
  context text not null check (context in ('universidad','trabajo','personal')),
  url     text not null            -- enlace .ics (secreto): no exponer públicamente
);

create table if not exists public.weekly_blocks (
  id          bigint generated by default as identity primary key,
  title       text not null,
  context     text not null default 'trabajo',
  days        text not null default '1,2,3,4,5',
  start_time  text not null default '08:00',
  end_time    text not null default '17:00',
  description text not null default '',
  active      integer not null default 1
);
alter table public.weekly_blocks enable row level security;

create table if not exists public.tasks (
  id           bigint generated by default as identity primary key,
  title        text not null,
  context      text not null default 'personal' check (context in ('universidad','trabajo','personal')),
  estimate_min integer not null default 60 check (estimate_min > 0),
  deadline     text not null,      -- ISO 8601 con zona horaria
  priority     integer not null default 2 check (priority between 1 and 3),
  done         integer not null default 0,
  description  text not null default '',
  completed_at text,
  source_uid   text unique,        -- UID del evento ICS importado (evita duplicados)
  created_at   timestamptz not null default now()
);
create index if not exists tasks_pending_idx on public.tasks (done, deadline);

create table if not exists public.time_logs (
  id        bigint generated by default as identity primary key,
  task_id   bigint not null references public.tasks(id) on delete cascade,
  minutes   integer not null check (minutes > 0),
  logged_at timestamptz not null default now()
);
create index if not exists time_logs_task_idx on public.time_logs (task_id);

create table if not exists public.notes (
  id         bigint generated by default as identity primary key,
  title      text not null default '',
  body       text not null default '',
  tags       text not null default '',
  task_id    bigint references public.tasks(id) on delete set null,
  canvas     text not null default '[]',        -- JSON: elementos de la nota
  color      text not null default '#FFF59D',
  pinned     integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Seguridad: activa RLS SIN políticas → la API pública de Supabase (clave anon)
-- no puede leer ni escribir nada. Solo el backend, que se conecta con la
-- cadena DATABASE_URL (rol postgres), accede a los datos.
alter table public.calendars  enable row level security;
alter table public.tasks      enable row level security;
alter table public.time_logs  enable row level security;
alter table public.notes      enable row level security;
